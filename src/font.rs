/// A word in the big font: 8 lines (unknown characters are skipped).
pub fn render(word: &str) -> Vec<String> {
    let mut rows = vec![String::new(); 8];
    for c in word.to_uppercase().chars() {
        if c == ' ' {
            for r in rows.iter_mut() {
                r.push_str("   ");
            }
            continue;
        }
        let Some((_, g)) = GLYPHS.iter().find(|(k, _)| *k == c) else { continue };
        let w = g.iter().map(|r| r.chars().count()).max().unwrap_or(0);
        for (i, r) in rows.iter_mut().enumerate() {
            let s = g[i];
            r.push_str(s);
            r.push_str(&" ".repeat(w - s.chars().count() + 1));
        }
    }
    rows
}
